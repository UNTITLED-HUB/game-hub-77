import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const files=JSON.parse(fs.readFileSync(path.join(root,'systems.json'),'utf8'));
const parts=files.map(name=>{const source=fs.readFileSync(path.join(root,name),'utf8');new vm.Script(source,{filename:name});return `// Source: ${name}\n${source.trim()}\n`;});
const output=`/* Generated by node build-game.mjs. Edit the system files listed in systems.json. */\n(()=>{\n'use strict';\n${parts.join('\n')}\n})();\n`;
new vm.Script(output,{filename:'game.js'});
const dest=path.join(root,'game.js');
if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8')!==output)throw Error('game.js is stale: run node build-game.mjs');console.log('Bundle matches all source systems.');}else{fs.writeFileSync(dest,output);console.log(`Built game.js from ${files.length} systems.`);}
